-- Flight-aware airport positioning (GSP first; CLT and ATL ready).
-- Additive: two tables, one run log, two functions. No trip column changes.
--
-- flight_arrivals   provider feed (scheduled / estimated / actual landing), written by the
--                   trip-sweeps 'flight-arrivals' step with the service role only.
--                   Rows exist only for what a real provider returned. No key = no rows.
-- flight_ingest_runs per-airport throttle + last provider status (5-minute cadence).
-- airport_wave_alerts dedupe for "stage at the cell lot" driver pushes.
-- airport_arrival_waves(airport, hours) 20-minute landing waves weighted by booked
--                   airport pickups with flight numbers. Drivers/admins/service role only.
--                   Heat map / surge can call it; it returns counts only, no rider data.
-- apply_trip_flight_status(trip, jsonb) atomic merge of metadata.flight_status (service role).

CREATE TABLE IF NOT EXISTS public.flight_arrivals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  airport text NOT NULL CHECK (airport IN ('GSP', 'CLT', 'ATL')),
  flight_number text NOT NULL CHECK (flight_number ~ '^[A-Z0-9]{2} [0-9]{1,4}[A-Z]?$'),
  flight_date date NOT NULL,
  airline_code text,
  origin text,
  status text,
  scheduled_at timestamptz,
  estimated_at timestamptz,
  actual_at timestamptz,
  terminal text,
  gate text,
  provider text NOT NULL,
  fetched_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flight_arrivals_unique UNIQUE (airport, flight_number, flight_date)
);
CREATE INDEX IF NOT EXISTS flight_arrivals_airport_eta_idx
  ON public.flight_arrivals (airport, (coalesce(actual_at, estimated_at, scheduled_at)));
ALTER TABLE public.flight_arrivals ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS flight_arrivals_driver_read ON public.flight_arrivals;
CREATE POLICY flight_arrivals_driver_read ON public.flight_arrivals
  FOR SELECT TO authenticated USING (public.is_driver_or_admin_role());
REVOKE ALL ON public.flight_arrivals FROM anon;
GRANT SELECT ON public.flight_arrivals TO authenticated;
GRANT ALL ON public.flight_arrivals TO service_role;

CREATE TABLE IF NOT EXISTS public.flight_ingest_runs (
  airport text PRIMARY KEY CHECK (airport IN ('GSP', 'CLT', 'ATL')),
  provider text NOT NULL,
  last_run_at timestamptz NOT NULL DEFAULT now(),
  rows_upserted integer NOT NULL DEFAULT 0,
  last_error text
);
ALTER TABLE public.flight_ingest_runs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.flight_ingest_runs FROM anon, authenticated;
GRANT ALL ON public.flight_ingest_runs TO service_role;

CREATE TABLE IF NOT EXISTS public.airport_wave_alerts (
  airport text NOT NULL,
  wave_start timestamptz NOT NULL,
  flights integer NOT NULL DEFAULT 0,
  booked_pickups integer NOT NULL DEFAULT 0,
  drivers_notified integer NOT NULL DEFAULT 0,
  sent_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (airport, wave_start)
);
ALTER TABLE public.airport_wave_alerts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.airport_wave_alerts FROM anon, authenticated;
GRANT ALL ON public.airport_wave_alerts TO service_role;

CREATE OR REPLACE FUNCTION public.airport_arrival_waves(
  p_airport text DEFAULT 'GSP',
  p_hours integer DEFAULT 3,
  p_now timestamptz DEFAULT NULL
)
RETURNS TABLE (
  airport text,
  wave_start timestamptz,
  wave_end timestamptz,
  stage_at timestamptz,
  flights integer,
  booked_pickups integer,
  score numeric,
  data_quality text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_now timestamptz := coalesce(p_now, now());
  v_air text := upper(coalesce(p_airport, 'GSP'));
  v_hours integer := greatest(1, least(coalesce(p_hours, 3), 12));
  v_name text;
BEGIN
  IF NOT (public.is_driver_or_admin_role() OR coalesce(auth.role(), '') = 'service_role') THEN
    RETURN;
  END IF;
  IF v_air NOT IN ('GSP', 'CLT', 'ATL') THEN RETURN; END IF;
  v_name := CASE v_air WHEN 'GSP' THEN '%greenville%spartanburg%' WHEN 'CLT' THEN '%charlotte%' ELSE '%hartsfield%' END;
  RETURN QUERY
  WITH feed AS (
    SELECT replace(f.flight_number, ' ', '') AS fkey,
           coalesce(f.actual_at, f.estimated_at, f.scheduled_at) AS eta,
           (f.estimated_at IS NOT NULL OR f.actual_at IS NOT NULL) AS live
    FROM public.flight_arrivals f
    WHERE f.airport = v_air
      AND lower(coalesce(f.status, '')) NOT IN ('canceled', 'cancelled', 'diverted')
      AND coalesce(f.actual_at, f.estimated_at, f.scheduled_at)
          BETWEEN v_now - interval '20 minutes' AND v_now + make_interval(hours => v_hours)
  ),
  booked AS (
    SELECT t.id,
           upper(regexp_replace(coalesce(t.metadata->'flight'->>'number', t.flight, ''), '\s+', '', 'g')) AS fkey,
           coalesce(t.scheduled_for, t.pickup_at) AS pickup_time
    FROM public.trips t
    WHERE t.status::text IN ('scheduled', 'searching', 'offered', 'accepted', 'arriving')
      AND (t.pickup_label ~* ('\m' || v_air || '\M') OR t.pickup_label ILIKE v_name
           OR upper(coalesce(t.metadata->>'airport', '')) = v_air)
      AND (t.dropoff_label IS NULL OR NOT (t.dropoff_label ~* ('\m' || v_air || '\M')))
      AND coalesce(t.metadata->'flight'->>'number', t.flight, '') <> ''
      AND coalesce(t.scheduled_for, t.pickup_at) BETWEEN v_now - interval '2 hours' AND v_now + interval '14 hours'
      AND coalesce((t.metadata->>'e2e_test')::boolean, false) = false
  ),
  booked_eta AS (
    SELECT b.id,
           coalesce((SELECT fe.eta FROM feed fe WHERE fe.fkey = b.fkey
                     ORDER BY abs(extract(epoch FROM fe.eta - b.pickup_time)) LIMIT 1), b.pickup_time) AS eta,
           EXISTS (SELECT 1 FROM feed fe WHERE fe.fkey = b.fkey AND fe.live) AS live
    FROM booked b
  ),
  points AS (
    SELECT fe.eta, 1 AS is_flight, 0 AS is_booked, fe.live, true AS from_feed FROM feed fe
    UNION ALL
    SELECT be.eta, 0, 1, be.live, false FROM booked_eta be
  ),
  binned AS (
    SELECT date_bin(interval '20 minutes', p.eta, timestamptz '2000-01-01 00:00:00+00') AS b, p.*
    FROM points p
  )
  SELECT v_air,
         bn.b,
         bn.b + interval '20 minutes',
         bn.b - interval '20 minutes',
         sum(bn.is_flight)::integer,
         sum(bn.is_booked)::integer,
         (sum(bn.is_flight) + 3 * sum(bn.is_booked))::numeric,
         CASE WHEN bool_or(bn.live) THEN 'live'
              WHEN bool_or(bn.from_feed) THEN 'scheduled'
              ELSE 'rider_entered' END
  FROM binned bn
  WHERE bn.b + interval '20 minutes' >= v_now AND bn.b <= v_now + make_interval(hours => v_hours)
  GROUP BY bn.b
  ORDER BY bn.b;
END;
$function$;

REVOKE ALL ON FUNCTION public.airport_arrival_waves(text, integer, timestamptz) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.airport_arrival_waves(text, integer, timestamptz) FROM anon;
GRANT EXECUTE ON FUNCTION public.airport_arrival_waves(text, integer, timestamptz) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.apply_trip_flight_status(p_trip_id uuid, p_status jsonb)
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
  WITH u AS (
    UPDATE public.trips
    SET metadata = coalesce(metadata, '{}'::jsonb) || jsonb_build_object('flight_status', p_status)
    WHERE id = p_trip_id
      AND (metadata->'flight_status') IS DISTINCT FROM p_status
    RETURNING 1
  )
  SELECT EXISTS (SELECT 1 FROM u);
$function$;

REVOKE ALL ON FUNCTION public.apply_trip_flight_status(uuid, jsonb) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.apply_trip_flight_status(uuid, jsonb) FROM anon;
REVOKE ALL ON FUNCTION public.apply_trip_flight_status(uuid, jsonb) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.apply_trip_flight_status(uuid, jsonb) TO service_role;

